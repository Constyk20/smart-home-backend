"""Database-facing ML service: collects history from MongoDB and calls app.services.ml_core.

All public functions that take owner_id verify house ownership first.
current_hour_probabilities() does not: its only caller (recommendation_service) has already
verified ownership.

Data source (matches app/services/activity_service.py): the "activity_logs" collection, where
device_state_changed entries carry house_id, device_id, created_at and payload["new_state"].
Changes made by automation also carry payload["rule_id"], which is how they are told apart.
"""
from __future__ import annotations

import asyncio
import logging
from datetime import datetime, timedelta, timezone
from typing import Any

import pandas as pd
from bson import ObjectId
from fastapi import HTTPException, status  # status is used for the 404 below

from app.db.mongodb import get_database
from app.models.ml import (
    AnomalyItem,
    AnomalyResponse,
    DevicePrediction,
    HourPrediction,
    ModelInfo,
    ModelMetrics,
    PredictionResponse,
)
from app.services import ml_core
from app.services.house_service import get_house_by_id

logger = logging.getLogger(__name__)

ACTIVITY_COLLECTION = "activity_logs"
STATE_CHANGE_ACTION = "device_state_changed"
AUTOMATION_SHARE_WARNING = 0.3


# ---------------------------------------------------------------------------
# Data collection
# ---------------------------------------------------------------------------

async def _load_history(
    house_id: str,
) -> tuple[list[dict[str, Any]], dict[str, str], dict[str, str]]:
    """Return (on/off events, device_id -> type, device_id -> name) for one house."""
    db = get_database()
    house_oid = ObjectId(house_id)

    device_types: dict[str, str] = {}
    device_names: dict[str, str] = {}
    async for device in db["devices"].find({"house_id": house_oid}):
        device_types[str(device["_id"])] = device.get("device_type", "other")
        device_names[str(device["_id"])] = device.get("name", "Device")

    events: list[dict[str, Any]] = []
    cursor = (
        db[ACTIVITY_COLLECTION]
        .find({"house_id": {"$in": [house_oid, house_id]}, "action": STATE_CHANGE_ACTION})
        .sort("created_at", 1)
    )
    async for doc in cursor:
        timestamp = doc.get("created_at")
        payload = doc.get("payload") or {}
        new_state = payload.get("new_state") or {}
        if timestamp is None or "is_on" not in new_state:
            continue
        if timestamp.tzinfo is None:
            timestamp = timestamp.replace(tzinfo=timezone.utc)
        events.append(
            {
                "device_id": str(doc.get("device_id")),
                "timestamp": timestamp,
                "is_on": bool(new_state["is_on"]),
                # Changes made by a rule or schedule rather than by the user.
                "automation": bool(payload.get("rule_id") or payload.get("schedule_id")),
                # Rows written by scripts/seed_synthetic_history.py, not by real use.
                "synthetic": bool(payload.get("synthetic")),
            }
        )
    return events, device_types, device_names


def _relevant(events: list[dict[str, Any]], device_types: dict[str, str]) -> list[dict[str, Any]]:
    return [e for e in events if device_types.get(e["device_id"]) in ml_core.MODEL_DEVICE_TYPES]


def _insufficient(detail: str) -> HTTPException:
    return HTTPException(status_code=422, detail=detail)


