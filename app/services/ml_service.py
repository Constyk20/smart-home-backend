async def predict_usage(house_id: str, owner_id: str, hours: int) -> PredictionResponse:
    await get_house_by_id(house_id, owner_id)
    loaded = await asyncio.to_thread(ml_core.load_model, house_id)
    if loaded is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No trained model for this house yet. Train one first.",
        )
    model, meta = loaded

    db = get_database()
    devices = [
        d
        async for d in db["devices"].find({"house_id": ObjectId(house_id)})
        if d.get("device_type") in ml_core.MODEL_DEVICE_TYPES
    ]
    first_hour = ml_core.local_now().replace(minute=0, second=0, microsecond=0) + timedelta(hours=1)

    rows: list[dict[str, Any]] = []
    for device in devices:
        for offset in range(hours):
            slot = first_hour + timedelta(hours=offset)
            rows.append(
                {
                    "device_id": str(device["_id"]),
                    "hour_start": slot,
                    "hour": slot.hour,
                    "dow": slot.weekday(),
                    "device_type": device["device_type"],
                }
            )
    frame = pd.DataFrame(rows)
    probabilities = ml_core.usage_probability(model, frame) if rows else []

    by_device: dict[str, list[HourPrediction]] = {}
    for row, probability in zip(rows, probabilities):
        by_device.setdefault(row["device_id"], []).append(
            HourPrediction(hour_start=row["hour_start"], probability_on=round(float(probability), 3))
        )

    beats = bool(meta["metrics"]["beats_majority_baseline"])
    return PredictionResponse(
        house_id=house_id,
        generated_at=datetime.now(timezone.utc),
        model_trained_at=datetime.fromisoformat(meta["trained_at"]),
        model_beats_baseline=beats,
        note=(
            "Estimated chance each device is normally ON in that hour (Lagos time), learned from "
            "this house's logged history. These are habit estimates, not certainties."
            + ("" if beats else " This model did not beat the baseline; treat it as unreliable.")
        ),
        predictions=[
            DevicePrediction(
                device_id=str(d["_id"]),
                device_name=d.get("name", "Device"),
                device_type=d["device_type"],
                hours=by_device.get(str(d["_id"]), []),
            )
            for d in devices
        ],
    )


async def current_hour_probabilities(house_id: str) -> tuple[dict[str, float], dict[str, Any], int] | None:
    """(device_id -> P(on) for the current local hour, model metadata, local hour).

    Returns None when there is no model or the model did not beat its baseline.
    Caller must already have verified that the user owns the house.
    """
    loaded = await asyncio.to_thread(ml_core.load_model, house_id)
    if loaded is None:
        return None
    model, meta = loaded
    if not meta["metrics"]["beats_majority_baseline"]:
        return None

    db = get_database()
    now_local = ml_core.local_now()
    rows = [
        {
            "device_id": str(d["_id"]),
            "hour": now_local.hour,
            "dow": now_local.weekday(),
            "device_type": d["device_type"],
        }
        async for d in db["devices"].find({"house_id": ObjectId(house_id)})
        if d.get("device_type") in ml_core.MODEL_DEVICE_TYPES
    ]
    if not rows:
        return {}, meta, now_local.hour
    probabilities = ml_core.usage_probability(model, pd.DataFrame(rows))
    return (
        {row["device_id"]: float(p) for row, p in zip(rows, probabilities)},
        meta,
        now_local.hour,
    )


