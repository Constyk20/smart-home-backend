async def find_anomalies(house_id: str, owner_id: str) -> AnomalyResponse:
    await get_house_by_id(house_id, owner_id)
    events, device_types, device_names = await _load_history(house_id)
    relevant = _relevant(events, device_types)
    if not relevant:
        raise _insufficient("No logged on/off changes for supported devices yet.")

    df = ml_core.build_hourly_dataset(relevant, device_types, datetime.now(timezone.utc))
    anomalies, checked, skipped = await asyncio.to_thread(ml_core.detect_anomalies, df)

    return AnomalyResponse(
        house_id=house_id,
        generated_at=datetime.now(timezone.utc),
        devices_checked=checked,
        devices_skipped=skipped,
        note=(
            f"A day is flagged when a device's runtime pattern is unusual compared with that same "
            f"device's own history. Devices need {ml_core.MIN_DAYS_PER_DEVICE} complete days of "
            "history to be checked. A flag means 'unusual', not 'faulty'."
        ),
        anomalies=[
            AnomalyItem(
                device_id=a["device_id"],
                device_name=device_names.get(a["device_id"], "Device"),
                date=a["date"],
                on_hours=round(a["on_hours"], 2),
                typical_on_hours=round(a["typical_on_hours"], 2),
                anomaly_score=round(a["anomaly_score"], 4),
            )
            for a in anomalies[:50]
        ],
    )
