def _info_from_meta(house_id: str, meta: dict[str, Any]) -> ModelInfo:
    notes: list[str] = []
    share = meta.get("automation_event_share", 0.0)
    if share > AUTOMATION_SHARE_WARNING:
        notes.append(
            f"{share:.0%} of the logged changes were made by rules or schedules, so the model "
            "partly reflects your automation rules rather than only your own habits."
        )
    if not meta["metrics"]["beats_majority_baseline"]:
        notes.append(
            "The model did not beat the always-guess-the-majority baseline on held-out data. "
            "Treat its predictions as unreliable. No ML recommendations are produced from it."
        )
    synthetic_share = meta.get("synthetic_event_share", 0.0)
    if synthetic_share > 0:
        notes.append(
            f"SYNTHETIC DATA: {synthetic_share:.0%} of the training history was generated by "
            "the seeding script. The metrics show how well the model learned that made-up routine, "
            "not how well it predicts real household behaviour."
        )
    notes.append(
        "Metrics come from the latest 20% of this house's history; the saved model is then "
        "refit on all of it."
    )
    return ModelInfo(
        house_id=house_id,
        trained=True,
        synthetic=synthetic_share > 0,
        trained_at=datetime.fromisoformat(meta["trained_at"]),
        model_type=meta["model_type"],
        metrics=ModelMetrics(**meta["metrics"]),
        n_events=meta["n_events"],
        automation_event_share=share,
        history_start=datetime.fromisoformat(meta["history_start"]),
        history_end=datetime.fromisoformat(meta["history_end"]),
        timezone=ml_core.LOCAL_TZ,
        notes=notes,
    )


async def get_model_info(house_id: str, owner_id: str) -> ModelInfo:
    await get_house_by_id(house_id, owner_id)
    loaded = await asyncio.to_thread(ml_core.load_model, house_id)
    if loaded is None:
        return ModelInfo(
            house_id=house_id,
            trained=False,
            notes=["No model has been trained for this house yet."],
        )
    return _info_from_meta(house_id, loaded[1])


async def train_for_house(house_id: str, owner_id: str) -> ModelInfo:
    await get_house_by_id(house_id, owner_id)
    events, device_types, _ = await _load_history(house_id)
    relevant = _relevant(events, device_types)
    if len(relevant) < ml_core.MIN_EVENTS:
        raise _insufficient(
            f"Only {len(relevant)} logged on/off changes for supported devices; "
            f"at least {ml_core.MIN_EVENTS} are needed before a model can be trained."
        )

    now = datetime.now(timezone.utc)
    df = ml_core.build_hourly_dataset(relevant, device_types, now)
    try:
        model, metrics = await asyncio.to_thread(ml_core.train_usage_model, df)
    except ml_core.InsufficientDataError as exc:
        raise _insufficient(str(exc)) from exc

    meta = {
        "house_id": house_id,
        "trained_at": now.isoformat(),
        "model_type": "RandomForestClassifier (hourly device habit)",
        "metrics": metrics,
        "n_events": len(relevant),
        "automation_event_share": sum(e["automation"] for e in relevant) / len(relevant),
        "synthetic_event_share": sum(e["synthetic"] for e in relevant) / len(relevant),
        "history_start": min(e["timestamp"] for e in relevant).isoformat(),
        "history_end": now.isoformat(),
        "features": ml_core.FEATURE_COLUMNS,
    }
    await asyncio.to_thread(ml_core.save_model, house_id, model, meta)
    return _info_from_meta(house_id, meta)


